const rows = Object.fromEntries(Object.entries(glyphs).map(([char, data]) => [char, data.split('/')]));
function chars(text: string) { return [...text.toUpperCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[’‘]/g, "'").replace(/[–—·]/g, '-')]; }
export function pixelTextWidth(text: string, scale = 1) { return Math.max(0, chars(text).reduce((sum, char) => sum + (rows[char] ?? rows['?'])[0].length + 1, 0) - 1) * scale; }
export function pixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, align: 'left' | 'center' | 'right' = 'left', scale = 1) {
  const width = pixelTextWidth(text, scale);
  let cursor = Math.round(x - (align === 'center' ? width / 2 : align === 'right' ? width : 0));
  const top = Math.round(y); ctx.fillStyle = color;
  for (const char of chars(text)) {
    const glyph = rows[char] ?? rows['?'];
    glyph.forEach((row, dy) => [...row].forEach((pixel, dx) => { if (pixel === '1') ctx.fillRect(cursor + dx * scale, top + dy * scale, scale, scale); }));
    cursor += (glyph[0].length + 1) * scale;
  }
}
